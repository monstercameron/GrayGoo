"""Persistent SBCL worker pool over a stdio s-expression protocol.

Issues.md #3 (pool is not persistent), #27 (no reset protocol), #28
(no health model). Where :func:`workers.run_lisp` spawns a fresh SBCL
per job, :class:`Pool` keeps ``size`` long-lived SBCL subprocesses and
drives each over a one-line-at-a-time ASCII protocol on stdio::

    pool -> worker   JOB <job-id> <prelude-b64|-> <code-b64>
    worker -> pool   RESULT <job-id> <json>
    pool -> worker   PING                  worker -> pool   PONG <worker-id>
    pool -> worker   RESET                 worker -> pool   RESET-OK sandbox=<yes|no>
                                                      (or RESET-FAIL <msg>)
    pool -> worker   BYE                   (worker exits 0)

Code travels base64 (UTF-8 inside) so the pipe never depends on locale
external-formats; results are ASCII-only JSON (``\\u``-escaped, same
shape as :func:`workers.run_lisp` plus ``worker_id``/``job_id``/
``generation``). The worker prints ``READY <worker-id>`` after boot;
anything before it is startup noise and is skipped.

Health, poison, recycle, reset, generation ownership:

* health: checkout-time liveness + ``PING`` when idle too long or every
  N jobs; failures destroy and replace the worker,
* poison: EOF, malformed ``RESULT`` (bad job id / bad JSON), timeout,
  or generation mismatch destroys the worker immediately — a wedged
  eval cannot be interrupted over stdio, so timeouts always kill,
* recycle: a worker is destroyed after ``max_jobs_per_worker`` jobs or
  ``max_age_s`` seconds (bounded lifetimes),
* reset: ``RESET`` deletes and recreates the per-job package (best
  effort — code that leaves the job package escapes it) and reports
  the sandbox state; hard recycle stays the real hygiene,
* generation: every worker is stamped with the pool generation
  (default: :func:`fingerprint.compute_string`); each ``RESULT`` echoes
  it and mismatches poison the worker; :meth:`Pool.regenerate`
  destroys the fleet for epoch changes.

Fallback: when a persistent worker cannot serve a job (spawn failure,
poison) and ``oneshot_fallback`` is true (default), that job is
delegated to :func:`workers.run_lisp` for a one-shot run. This is the
only sanctioned call into the sibling-owned :mod:`workers` module, and
it is call-only — this file never edits it.

Secret hygiene: spawned workers get a scrubbed environment
(:func:`_scrub_env` removes ``CEREBRAS_API_KEY``/``CEREBRAS``); the
worker script embeds no secrets. See ``documents/secret-policy.md``.

Stdlib plus optional repo siblings (``sandbox`` for the boot prelude,
``fingerprint`` for the default generation, ``workers`` for one-shot
fallback) — every sibling import degrades gracefully when absent.
"""

