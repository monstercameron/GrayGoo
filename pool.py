class WorkerError(Exception):
    """Base class for pool worker failures."""


class WorkerSpawnError(WorkerError):
    """A persistent worker could not be spawned or readied."""


class WorkerPoisonedError(WorkerError):
    """A worker desynced, timed out, or failed health and was destroyed."""


class TargetFrozenError(WorkerError):
    """Reserved: pool-side refusal hook (storm integration point)."""


